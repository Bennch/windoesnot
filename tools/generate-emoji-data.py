#!/usr/bin/env python3
"""Generate desktop/config/quickshell/default/EmojiData.js from the unicode_codes folder of the python-emoji package.

usage: tools/generate-emoji-data.py <path to emoji/unicode_codes>
One entry per emoji (fully qualified, no skin-tone variants), with English and German names for the search."""
import json
from pathlib import Path
import re
import sys

source = Path(sys.argv[1])
english = json.loads((source / 'emoji.json').read_text())
german = json.loads((source / 'emoji_de.json').read_text())
SKIN = re.compile('[\U0001F3FB-\U0001F3FF]')


def words(name):
    return re.sub(r'\s+', ' ', name.strip(':').replace('_', ' ').replace('-', ' ')).strip()


def rank(code):
    """Rough Unicode-block order that reads like an emoji keyboard: faces first, flags and keycaps last."""
    if 0x1F600 <= code <= 0x1F64F or 0x1F910 <= code <= 0x1F92F or 0x1F970 <= code <= 0x1F97F or 0x1FAE0 <= code <= 0x1FAEF:
        return 0
    if 0x1F440 <= code <= 0x1F4FF or 0x1F90C <= code <= 0x1F90F or 0x1F930 <= code <= 0x1F9FF:
        return 1
    if 0x1F300 <= code <= 0x1F3FF or 0x1F400 <= code <= 0x1F43F or 0x1F680 <= code <= 0x1F6FF or 0x1F7E0 <= code <= 0x1F7FF:
        return 2
    if 0x1F500 <= code <= 0x1F5FF or 0x1FA70 <= code <= 0x1FAFF:
        return 3
    if 0x1F1E6 <= code <= 0x1F1FF:
        return 6
    if code < 0x100:
        return 5
    return 4


rows = []
for emoji, data in english.items():
    if data['status'] != 2 or SKIN.search(emoji):   # fully qualified only, skin tones left to the base emoji
        continue
    rows.append((rank(ord(emoji[0])), ord(emoji[0]), len(emoji), emoji, words(data['en']), words(german.get(emoji, ''))))
rows.sort()
lines = [f'{emoji}\t{en}\t{de}' for _r, _o, _l, emoji, en, de in rows]
out = Path(__file__).resolve().parents[1] / 'desktop/config/quickshell/default/EmojiData.js'
out.write_text('.pragma library\n\n// Generated by tools/generate-emoji-data.py (python-emoji data, Unicode CLDR names). One line per emoji: symbol, English name, German name.\n'
               'var emoji = ' + json.dumps(lines, ensure_ascii=False, indent=0).replace('\n', '\n') + '\n')
print(len(rows), 'emoji', out.stat().st_size, 'bytes')
