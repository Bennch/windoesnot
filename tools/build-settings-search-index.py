#!/usr/bin/env python3
"""Generate settings/SearchIndex.js: which i18n keys and fixed texts appear on
which Settings page. Run after adding or moving settings; --check verifies it."""
import argparse
import json
from pathlib import Path
import re
import sys

QS = Path(__file__).resolve().parent.parent / 'desktop/config/quickshell/default'
OUT = QS / 'settings/SearchIndex.js'
# Page -> files that render it (see the Loaders in Settings.qml and nested pages).
PAGES = {
    'desktop': ['DesktopCategory'],
    'monitors': ['MonitorsCategory'],
    'background': ['BackgroundCategory'],
    'appearance': ['AppearanceCategory', 'ColorsCategory', 'StartOrbSettings'],
    'alignment': ['AlignmentCategory'],
    'input': ['InputCategory'],
    'power': ['PowerCategory'],
    'apps': ['AppsCategory', 'ShellSettings'],
    'maintenance': ['SystemCategory', 'MaintenanceCategory', 'KernelCategory'],
    'backups': ['BackupsCategory'],
    'updates': ['UpdateCategory'],
    'about': ['AboutCategory'],
    'help': ['HelpCategory'],
}
# Settings that live in a panel opened from a page: found under that page.
EXTRA_KEYS = {'power': ['power.brightness', 'power.nightLight']}
# Extra search words for settings people name differently than the label does.
SYNONYMS = {'power.nightLight': 'nachtlicht nachtmodus blaulicht night light blue light', 'power.brightness': 'dimmen heller dunkler dim', 'background.sddmThemeTitle': 'login sddm anmeldung lockscreen', 'apps.shellTitle': 'bash fish zsh terminal'}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='fail if SearchIndex.js is out of date')
args = parser.parse_args()

known = set(re.findall(r'^\s*"([^"]+)"\s*:', (QS / 'i18n/de.js').read_text(), re.M))
# Status and result messages are not settings; leave them out of the search.
noise = re.compile(r'(Saved|Error|Failed|Loading|Done|Working|Busy|Result|Toast|Progress|Confirm|Unavailable|Unknown)$|^(state|systemTools\.)', re.I)
key_re = re.compile(r'["\']([A-Za-z][A-Za-z0-9]*\.[A-Za-z0-9_]+)["\']')
lit_re = re.compile(r'\b(?:text|title|label|description|placeholderText)\s*:\s*"([^"\\]{3,120})"')
entries = []
for page, files in PAGES.items():
    keys, texts = [], []
    for name in files:
        source = (QS / 'settings' / (name + '.qml')).read_text()
        for key in key_re.findall(source):
            if key in known and key not in keys and not key.startswith(('nav.', 'header.', 'common.')) and not noise.search(key.split('.',1)[1] if '.' in key else key) and not key.startswith('systemTools.'):
                keys.append(key)
        for text in lit_re.findall(source):
            if text in known:
                if text not in keys:
                    keys.append(text)
            elif re.search(r'[A-Za-zÄÖÜäöü]{3}', text) and not re.search(r'["#{}$\\/]|^img', text) and text not in texts:
                texts.append(text)
    keys += [k for k in EXTRA_KEYS.get(page, []) if k in known and k not in keys]
    entries.append({'page': page, 'keys': keys, 'texts': texts, 'extra': {k: SYNONYMS[k] for k in keys if k in SYNONYMS}})
body = '// Generated by tools/build-settings-search-index.py; do not edit.\n.pragma library\nvar PAGES = ' + json.dumps(entries, ensure_ascii=False, indent=1) + '\n'
if args.check:
    sys.exit(0 if OUT.exists() and OUT.read_text() == body else 'settings/SearchIndex.js is out of date')
OUT.write_text(body)
print(OUT, sum(len(e['keys']) + len(e['texts']) for e in entries), 'entries')
for e in entries:
    print(' %-12s %3d keys %2d texts' % (e['page'], len(e['keys']), len(e['texts'])))
