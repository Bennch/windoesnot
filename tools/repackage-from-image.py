#!/usr/bin/env python3
"""Rebuild installable .pkg.tar.zst files from the pacman database of a finished image.

The repository must carry exactly the bits the ISO shipped (same version, same
binaries). The project packages are built inside the image, and their build
outputs are discarded, so this reads each package's `desc`, `files`, `mtree`
and `install` records and the installed files from the image root.
Run under `podman unshare` so rootless-build files read as root-owned."""
import argparse, gzip, io, os, subprocess, sys, tarfile
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--image', type=Path, required=True, help='.../work/x86_64/airootfs')
parser.add_argument('--output', type=Path, required=True)
parser.add_argument('packages', nargs='+', help='installed package names')
args = parser.parse_args()
db = args.image / 'var/lib/pacman/local'
args.output.mkdir(parents=True)

def sections(text):
    out, key = {}, None
    for line in text.splitlines():
        if line.startswith('%') and line.endswith('%'):
            key = line.strip('%'); out[key] = []
        elif line and key: out[key].append(line)
    return out

for name in args.packages:
    entry = next(p for p in db.iterdir() if p.name.rsplit('-', 2)[0] == name)
    desc = sections((entry / 'desc').read_text())
    files = [l for l in (entry / 'files').read_text().splitlines()[1:] if l and not l.startswith('%')]
    one = lambda k: desc[k][0] if desc.get(k) else None
    info = ['# Generated by repackage-from-image.py from a finished image',
            f'pkgname = {name}', f"pkgbase = {one('BASE') or name}", f"pkgver = {one('VERSION')}"]
    if one('DESC'): info.append(f"pkgdesc = {one('DESC')}")
    if one('URL'): info.append(f"url = {one('URL')}")
    info += [f"builddate = {one('BUILDDATE')}", f"packager = {one('PACKAGER') or 'Unknown Packager'}",
             f"size = {one('SIZE')}", f"arch = {one('ARCH')}"]
    for key, field in (('LICENSE', 'license'), ('REPLACES', 'replaces'), ('CONFLICTS', 'conflict'), ('PROVIDES', 'provides'),
                       ('DEPENDS', 'depend'), ('OPTDEPENDS', 'optdepend'), ('MAKEDEPENDS', 'makedepend')):
        info += [f'{field} = {v}' for v in desc.get(key, [])]
    info += [f"backup = {v.split(chr(9))[0]}" for v in desc.get('BACKUP', [])]
    info.append('xdata = pkgtype=pkg')
    version = one('VERSION'); arch = one('ARCH')
    target = args.output / f'{name}-{version}-{arch}.pkg.tar'
    with tarfile.open(target, 'w', format=tarfile.PAX_FORMAT) as tar:
        def add_bytes(path, data, mode=0o644):
            ti = tarfile.TarInfo(path); ti.size = len(data); ti.mode = mode; ti.uid = ti.gid = 0; ti.uname = ti.gname = 'root'
            ti.mtime = int(one('BUILDDATE')); tar.addfile(ti, io.BytesIO(data))
        add_bytes('.PKGINFO', ('\n'.join(info) + '\n').encode())
        mtree = entry / 'mtree'
        if mtree.exists(): add_bytes('.MTREE', mtree.read_bytes())
        if (entry / 'install').exists(): add_bytes('.INSTALL', (entry / 'install').read_bytes())
        for rel in files:
            path = args.image / rel.rstrip('/')
            ti = tar.gettarinfo(str(path), rel.rstrip('/'))
            ti.uid = ti.gid = 0; ti.uname = ti.gname = 'root'
            if ti.isreg():
                with open(path, 'rb') as stream: tar.addfile(ti, stream)
            else: tar.addfile(ti)
    subprocess.run(['zstd', '-q', '-19', '-T0', '--rm', str(target)], check=True)
    print(name, version, 'files', len(files))
